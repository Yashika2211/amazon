// Bundles ui-src/card.ts into a single self-contained HTML string for the MCP Apps resources.
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = await build({
  entryPoints: [join(root, "ui-src/card.ts")],
  bundle: true,
  minify: true,
  format: "iife",
  platform: "browser",
  target: "es2020",
  write: false,
});
const js = out.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const css = `
:root{--bg:#fffdf8;--fg:#1d1b16;--muted:#5d5848;--ok:#1f7a3d;--warn:#9a5b00;--bad:#b3261e;--chip:#efe9dc}
@media (prefers-color-scheme:dark){:root{--bg:#16140f;--fg:#f5f1e6;--muted:#c9c2ae;--ok:#6fd38f;--warn:#ffc266;--bad:#ff8a80;--chip:#2a271f}}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--fg);font:600 22px/1.35 system-ui,-apple-system,"Segoe UI",sans-serif;padding:20px}
h1{font-size:30px;margin:0 0 14px}.list{list-style:none;margin:0;padding:0}
.list li{display:flex;align-items:center;gap:14px;padding:12px 0;border-bottom:1px solid var(--chip)}
.time{min-width:96px;color:var(--muted)}.name{flex:1}small{font-weight:500;color:var(--muted)}
.chip{padding:6px 14px;border-radius:999px;background:var(--chip);font-size:18px;min-height:36px;display:inline-flex;align-items:center}
.chip.taken{color:var(--ok)}.chip.missed{color:var(--bad)}.chip.late,.chip.due{color:var(--warn)}
.digest{font-weight:500;color:var(--fg)}.appt{color:var(--muted)}.alert{color:var(--bad);font-size:24px}
`;
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>KinLoop</title><style>${css}</style></head><body><div id="root"><p class="digest">Loading…</p></div><script>${js}</script></body></html>`;
writeFileSync(
  join(root, "src/mcp/ui-html.generated.ts"),
  `// Generated by scripts/build-ui.mjs. Do not edit.\nexport const CARD_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`ui card: ${(html.length / 1024).toFixed(1)} KiB`);
